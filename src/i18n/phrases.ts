const exactKeys = Object.keys(exact).sort((a, b) => b.length - a.length);

export function translatePhrase(locale: Locale, text: string): string {
  if (locale === "en" || text === "") return text;
  const direct = exact[text];
  if (direct) return direct;
  for (const pattern of patterns) {
    const match = pattern.re.exec(text);
    if (match) return pattern.to(match);
  }
  let result = text;
  for (const key of exactKeys) {
    if (key.length < 12 || !result.includes(key)) continue;
    result = result.split(key).join(exact[key] ?? key);
  }
  return result;
}
